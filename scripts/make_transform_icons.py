#!/usr/bin/env python3
"""Generates tools/renderhamgui/TransformIcons.hpp: four 24x24 alpha masks
(rotate left/right, mirror horizontally/vertically) for the buttons under the
source picture.

Why masks instead of Unicode arrows in the button text: in the test environment
the buttons stayed empty (glyph not found). An alpha mask needs no font and is
tinted with the theme's text color at run time, so it is also readable on dark
themes.

Usage:  python3 scripts/make_transform_icons.py        (needs Pillow)
"""
import math, os
from PIL import Image, ImageDraw

N, SS = 24, 8            # target size, oversampling
S = N * SS

def canvas():
    return Image.new("L", (S, S), 0)

def finish(img):
    small = img.resize((N, N), Image.LANCZOS)
    return list(small.tobytes())

def rotate_right():
    im = canvas(); d = ImageDraw.Draw(im)
    cx = cy = S / 2; r = S * 0.30; w = int(S * 0.10)
    # Arc of 280 degrees, clockwise, open at the lower right
    start, end = 120, 400                      # PIL angles: 0 = right, increasing clockwise
    d.arc((cx - r, cy - r, cx + r, cy + r), start, end, fill=255, width=w)
    a = math.radians(end)                      # arrow head at the end of the arc, pointing along the tangent (clockwise)
    px, py = cx + r * math.cos(a), cy + r * math.sin(a)
    tx, ty = -math.sin(a), math.cos(a)         # tangent
    nx, ny = math.cos(a), math.sin(a)          # normal (outwards)
    L, W = S * 0.20, S * 0.15
    tip = (px + tx * L * 0.6, py + ty * L * 0.6)
    b1 = (px - tx * L * 0.4 + nx * W, py - ty * L * 0.4 + ny * W)
    b2 = (px - tx * L * 0.4 - nx * W, py - ty * L * 0.4 - ny * W)
    d.polygon([tip, b1, b2], fill=255)
    return im

def flip_h():
    im = canvas(); d = ImageDraw.Draw(im)
    m = S / 2; top, bot = S * 0.14, S * 0.86
    # dashed axis
    seg = (bot - top) / 7
    for i in range(0, 7, 2):
        d.rectangle((m - S * 0.025, top + i * seg, m + S * 0.025, top + (i + 1) * seg), fill=255)
    d.polygon([(m - S * 0.10, S * 0.22), (m - S * 0.10, S * 0.78), (S * 0.10, S * 0.78)], fill=255)   # left: filled
    d.polygon([(m + S * 0.10, S * 0.22), (m + S * 0.10, S * 0.78), (S * 0.90, S * 0.78)], outline=255, width=int(S * 0.05))  # right: outline only
    return im

icons = {
    "kIconRotateRight": finish(rotate_right()),
    "kIconRotateLeft": finish(rotate_right().transpose(Image.FLIP_LEFT_RIGHT)),
    "kIconFlipHorizontal": finish(flip_h()),
    "kIconFlipVertical": finish(flip_h().transpose(Image.ROTATE_90)),
}

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools", "renderhamgui", "TransformIcons.hpp")
with open(out, "w") as f:
    f.write("// SPDX-License-Identifier: MIT\n")
    f.write("// Copyright (c) 2026 rawbit (@ravvbit). AI-generated with Claude (Anthropic) under human direction; see README.md.\n")
    f.write("// Generated by scripts/make_transform_icons.py - do not edit by hand.\n")
    f.write("// 24x24 alpha masks; tinted with the theme's text color at run time.\n#pragma once\n\n")
    f.write("constexpr int kTransformIconSize = %d;\n\n" % N)
    for name, data in icons.items():
        f.write("constexpr unsigned char %s[%d] = {\n" % (name, N * N))
        for r in range(N):
            f.write("    " + ", ".join("%3d" % v for v in data[r * N:(r + 1) * N]) + ",\n")
        f.write("};\n\n")
# Preview for looking at
prev = Image.new("L", (N * 4 * 4, N * 4), 255)
for i, (name, data) in enumerate(icons.items()):
    im = Image.new("L", (N, N)); im.putdata([255 - v for v in data])
    prev.paste(im.resize((N * 4, N * 4), Image.NEAREST), (i * N * 4, 0))
outdir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "testdata", "out")
os.makedirs(outdir, exist_ok=True)
prev.save(os.path.join(outdir, "transform_icons_preview.png"))
print("written:", os.path.normpath(out))
